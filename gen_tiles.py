"""Generate src/tiles.h + src/rooms.h for SEVENFOLD from ASCII art.

Art rules (jam: TWO COLORS ONLY): every tile row uses only '.' (white,
GB shade 0) and '#' (black, GB shade 3). The generator asserts this, and
each tile row's low/high bytes are identical, so with the default BGP
palette (0xE4) only shades 0 and 3 ever appear on screen.
"""
import os

