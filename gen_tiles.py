def main():
    os.makedirs(os.path.dirname(OUT_TILES), exist_ok=True)
    scene_data = []
    with open(OUT_TILES, "w") as fh:
        fh.write("/* Generated by gen_tiles.py - do not edit by hand. */\n")
        for i, (name, rows) in enumerate(SCENE):
            fh.write(f"#define {name} {i}\n")
            scene_data += tile_bytes(rows, name)
        fh.write(f"#define SCENE_COUNT {len(SCENE)}\n")
        emit_array(fh, "scene_tiles", scene_data)
        font_data = []
        for ch in FONT_ORDER:
            assert ch in FONT, f"missing glyph for {ch!r}"
            font_data += tile_bytes(FONT[ch], f"font {ch!r}")
        fh.write(f"#define FONT_BASE SCENE_COUNT\n")
        fh.write(f"#define FONT_COUNT {len(FONT_ORDER)}\n")
        emit_array(fh, "font_tiles", font_data)
        port_data = []
        for si, stage in enumerate(PORTRAITS):
            assert len(stage) == 16, f"portrait {si}: need 16 rows"
            for r in stage:
                assert len(r) == 16, f"portrait {si}: row {r!r} not 16 chars"
                assert set(r) <= {".", "#"}
            quads = []
            for qy in (0, 1):
                for qx in (0, 1):
                    quads.append([stage[qy * 8 + dy][qx * 8:qx * 8 + 8]
                                  for dy in range(8)])
            for q in quads:
                port_data += tile_bytes(q, f"portrait {si}")
        fh.write("#define PORT_BASE (FONT_BASE + FONT_COUNT)\n")
        fh.write("#define PORT_COUNT 16\n")
        emit_array(fh, "portrait_tiles", port_data)
        fh.write("#define SPR_CURSOR_TILE 200\n")
        emit_array(fh, "cursor_tile", tile_bytes(CURSOR, "cursor"))

    # rooms.h: room maps, validated to 12 rows x 20 cols
    rooms = ROOM_MAPS + [TITLE_MAP]
    with open(OUT_ROOMS, "w") as fh:
        fh.write("/* Generated by gen_tiles.py - do not edit by hand. */\n")
        fh.write("static const char room_maps[][12][21] = {\n")
        for ri, rows in enumerate(rooms):
            assert len(rows) == 12, f"room {ri}: need 12 rows"
            fh.write("  {\n")
            for r in rows:
                assert len(r) == 20, f"room {ri}: row {r!r} not 20 chars"
                fh.write(f'    "{r}",\n')
            fh.write("  },\n")
        fh.write("};\n")
        fh.write(f"#define ROOM_COUNT {len(rooms) - 1}\n")
        fh.write(f"#define TITLE_MAP_INDEX {len(rooms) - 1}\n")
    print(f"wrote {OUT_TILES} and {OUT_ROOMS}")


