OUT_TILES = os.path.join(HERE, "src", "tiles.h")
OUT_ROOMS = os.path.join(HERE, "src", "rooms.h")


def tile_bytes(rows, name):
    assert len(rows) == 8, f"{name}: need 8 rows, got {len(rows)}"
    out = []
    for r in rows:
        assert len(r) == 8, f"{name}: row {r!r} is not 8 chars"
        assert set(r) <= {".", "#"}, f"{name}: bad char in {r!r}"
        b = 0
        for ch in r:
            b = (b << 1) | (1 if ch == "#" else 0)
        out.append(b)
        out.append(b)  # low byte == high byte -> pixel values only 0 or 3
    return out


def emit_array(fh, name, data):
    fh.write(f"static const unsigned char {name}[] = {{\n")
    for i in range(0, len(data), 16):
        fh.write("  " + ",".join(f"0x{b:02X}" for b in data[i:i + 16]) + ",\n")
    fh.write("};\n")


